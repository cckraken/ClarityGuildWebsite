using ClarityGuildWebsite.Api.Helpers;
using ClarityGuildWebsite.Api.Models;
using System.Text.Json;

namespace ClarityGuildWebsite.Api.Services
{
    public class DiscordWebhookNotifier : IApplicationNotifier
    {
        private readonly HttpClient _http;
        private readonly string _webhookUrl;
        private const int EmbedColour = 0x0094fe;
        private const string Footer = "Auto generated by the Clarity API";

        public DiscordWebhookNotifier(HttpClient http, IConfiguration config)
        {
            _http = http;
            _webhookUrl = config["Discord:WebhookUrl"] ?? throw new InvalidOperationException("Discord:WebhookUrl is not configured.");          
        }

        public async Task<NotificationResult> PostAndRecordAsync(GuildApplication application, CancellationToken ctoken)
        {
            var embed = new DiscordEmbed(
                Title: "New Application " + application.MainName,
                Fields:
                [
                   new("Main", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯"),
                   new("Main Character", ApplicationHelpers.Combine(application.MainName, application.MainRealm, application.MainRole), true),
                   new("Main Wlogs Link", ApplicationHelpers.LinkBuilder(application.MainName, application.MainRealm).wlogs, true),
                   new("Main IO Link", ApplicationHelpers.LinkBuilder(application.MainName, application.MainRealm).rio, true),
                   new("\u200B", "\u200B"),
                   new("Alt", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯"),
                   new("Alt Character", ApplicationHelpers.Combine(application.AltName, application.AltRealm, application.AltRole), true),
                   new("Alt Wlogs Link", ApplicationHelpers.LinkBuilder(application.AltName, application.AltRealm).wlogs, true),
                   new("Alt IO Link", ApplicationHelpers.LinkBuilder(application.AltName, application.AltRealm).rio, true), 
                   new("\u200B", "\u200B"),
                   new("Personal Info", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯"),
                   new("Discord Name", application.DiscordName, true),
                   new("Country", application.Country, true),
                   new("Age", application.Age?.ToString() ?? "Not provided", true),
                   new("Tech", application.Tech, false),
                   new("About", ApplicationHelpers.Truncate(application.About, 1024), false),
                   new("Preparation", ApplicationHelpers.Truncate(application.Preparation ?? "Not provided", 1024), false),
                   new("History", ApplicationHelpers.Truncate(application.History, 1024), false),
                ],
                Color: EmbedColour,
                Timestamp: new DateTimeOffset(application.TimestampUtc, TimeSpan.Zero),
                Footer: new DiscordEmbedFooter(Footer)
                );
            if (string.IsNullOrWhiteSpace(application.Extra))
                embed.Fields.Add(new("Extra", "N/A"));
            else
            {
                embed.Fields.Add(new("Extra", ApplicationHelpers.Truncate(application.Extra, 1024)));
            }
            try
            {
                var payload = new DiscordPayload(Embeds: new List<DiscordEmbed> { embed });
                using var response = await _http.PostAsJsonAsync(_webhookUrl + "?wait=true", payload, ctoken);
                if (!response.IsSuccessStatusCode)
                {
                    var body = await response.Content.ReadAsStringAsync(ctoken);
                    return NotificationResult.Failed($"{(int)response.StatusCode}: {body}");
                }
                else
                {
                    var message = await response.Content.ReadFromJsonAsync<DiscordMessageResponse>(ctoken);
                    if (string.IsNullOrEmpty(message?.Id))
                        return NotificationResult.Failed("Discord accepted the post but returned no message ID");

                    return NotificationResult.Delivered(message.Id, null);
                }
            }
            catch (HttpRequestException ex)
            {
                return NotificationResult.Failed($"Discord cannot be reached: {ex.Message}");
            }
            catch (TaskCanceledException ex)
            {
                if(ctoken.IsCancellationRequested)
                {
                    return NotificationResult.Failed($"User canceled operation: {ex.Message}");
                }
                else return NotificationResult.Failed($"Request timed out: {ex.Message}");
            }
            catch (JsonException ex)
            {
                return NotificationResult.Failed($"Discord's reponse was not valid JSON: {ex.Message}");
            }
        }
    }
}
