using ClarityGuildWebsite.Api.Helpers;
using ClarityGuildWebsite.Api.Models;
using Discord;
using Discord.Rest;
using System.Linq.Expressions;

namespace ClarityGuildWebsite.Api.Services
{
    public class DiscordBotNotifier : IApplicationNotifier
    {
        private readonly DiscordBotConnectionService _connection;
        private readonly ulong _channelId;
        private readonly ulong _officerRoleId;
        private readonly ILogger _logger;
        private const int EmbedColour = 0x0094fe;
        private const string Footer = "Auto generated by CCK";
        public DiscordBotNotifier(DiscordBotConnectionService connection, IConfiguration config, ILogger<DiscordBotNotifier> logger)
        {
            _connection = connection;
            _logger = logger;
            _channelId = config.GetValue<ulong>("Discord:ApplicationsChannelId");
            if (_channelId == 0)
                throw new InvalidOperationException("Discord:ApplicationsChannelId is missing or invalid.");
            _officerRoleId = config.GetValue<ulong>("Discord:OfficerRoleId");
            if (_officerRoleId == 0)
                throw new InvalidOperationException("Discord:OfficerRoleId is missing or invalid.");
        }

        public async Task<NotificationResult> PostAndRecordAsync(GuildApplication application, CancellationToken ctoken)
        {
            try
            {
                var client = await _connection.GetClientAsync();
                var options = new RequestOptions { CancelToken = ctoken };
                var channel = await client.GetChannelAsync(_channelId, options);
                if (channel is not ITextChannel textChannel)
                {
                    _logger.LogError("Channel {ChannelId} not found or is not a text channel", _channelId);
                    return new NotificationResult(false, null, "ChannelId not fond or is not a text channel");
                }


                var embed = ConstructEmbed(application);
                var message = await textChannel.SendMessageAsync(embed: embed, options: options);
                _logger.LogInformation("Application posted with message ID: {MessageId}", message.Id);
                try
                {
                    var threadName = $"New Application - {application.MainName}";
                    var thread = await textChannel.CreateThreadAsync(
                        name: threadName, message: message,
                        options: options,
                        autoArchiveDuration: ThreadArchiveDuration.OneWeek);
                    _logger.LogInformation("Thread {ThreadId} created for {PublicId}", thread.Id, application.PublicId);
                    await NotifyOfficersAsync(thread, options);
                }
                catch (Exception ex)
                {
                    _logger.LogWarning(ex, "Posted {PublicId} but failed to create its thread", application.PublicId);
                }

                return new NotificationResult(true, message.Id.ToString(), null);
            }
            catch (HttpRequestException ex)
            {
                _logger.LogError(ex, "Discord API unreachable");
                return new NotificationResult(false, null, $"Discord unreachable: {ex.Message}");
            }
            catch (TaskCanceledException ex)
            {
                _logger.LogWarning(ex, "Request timeout");
                return new NotificationResult(false, null, "Request timed out");
            }
            catch (Discord.Net.HttpException ex)
            {
                _logger.LogWarning(ex, "Required permissions missing on discord");
                return new NotificationResult(false, null, $"Required permissions missing on discord: {ex.Message}");
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error posting application to Discord");
                return new NotificationResult(false, null, $"Error: {ex.Message}");
            }
        }

        private async Task NotifyOfficersAsync(IThreadChannel thread, RequestOptions options)
        {
            try
            {
                await thread.SendMessageAsync($"New application! <@&{_officerRoleId}>", allowedMentions: new AllowedMentions { RoleIds = new List<ulong> { _officerRoleId } }, options: options);
                _logger.LogInformation("Officers notified in thread {ThreadId}", thread.Id);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Failed to notify officers in thread {ThreadId}", thread.Id);
            }
        }

        private Embed ConstructEmbed(GuildApplication application)
        {
            var TimeStampEmbed = new DateTimeOffset(application.TimestampUtc, TimeSpan.Zero);
            var mainLinks = ApplicationHelpers.LinkBuilder(application.MainName, application.MainRealm);
            var altLinks = ApplicationHelpers.LinkBuilder(application.AltName, application.AltRealm);

            var embed = new EmbedBuilder
            {

                Title = "New Application: " + (application.MainName),
                Color = new Color(EmbedColour),
                Timestamp = TimeStampEmbed,
                Footer = new EmbedFooterBuilder { Text = Footer }
            };
            embed.AddField("Main", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯", false)
            .AddField("Main Character", ApplicationHelpers.Combine(application.MainName, application.MainRealm, application.MainRole), true)
            .AddField("Links", $"[Warcraft Logs]({mainLinks.wlogs}) · [Raider.IO]({mainLinks.rio})", true)
            .AddField("UI Screenshot", application.Screenshot, false)
                    .AddField("Alt", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯")
                    .AddField("Alt Character", ApplicationHelpers.Combine(application.AltName, application.AltRealm, application.AltRole), true)
                    .AddField("Links", $"[Warcraft Logs]({altLinks.wlogs}) · [Raider.IO]({altLinks.rio})", true)
                    .AddField("Personal Info", "⎯⎯⎯⎯⎯⎯⎯⎯⎯⎯")
                    .AddField("Discord ID", application.DiscordId, true)
                    .AddField("Country", application.Country, true)
                    .AddField("Tech", application.Tech, false)
                    .AddField("About", ApplicationHelpers.Truncate(application.About, 1024), false)
                    .AddField("History", ApplicationHelpers.Truncate(application.History, 1024), false);

            if (string.IsNullOrWhiteSpace(application.Extra))
                embed.AddField("Extra", "N/A");
            else
                embed.AddField("Extra", ApplicationHelpers.Truncate(application.Extra, 1024));

            return embed.Build();
        }
    }
}